#!/usr/bin/env node
// Regenerates packages/cli/src/bench-corpus/default-recipes.ts from the
// canonical registry under packages/registry/recipes. Run via `pnpm gen:bench`
// whenever the registry's recipe set changes so `shortwind bench --corpus`
// keeps measuring against the shipped catalog rather than a frozen snapshot.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const RECIPES_DIR = path.resolve(here, "..", "..", "registry", "recipes");
const OUT_FILE = path.resolve(here, "..", "src", "bench-corpus", "default-recipes.ts");

const files = readdirSync(RECIPES_DIR).filter((f) => f.endsWith(".css")).sort();

const entries: string[] = [];
for (const file of files) {
  const source = readFileSync(path.join(RECIPES_DIR, file), "utf8");
  entries.push(`  ${JSON.stringify(file)}: ${JSON.stringify(source)},`);
}

const body = [
  `// Generated by scripts/generate-bench-recipes.ts. Do not edit directly —`,
  `// re-run \`pnpm --filter shortwind gen:bench\` after editing files under`,
  `// packages/registry/recipes/.`,
  `export const DEFAULT_RECIPES_CSS: Record<string, string> = {`,
  ...entries,
  `};`,
  ``,
].join("\n");

writeFileSync(OUT_FILE, body);
console.log(`Wrote ${OUT_FILE} (${files.length} recipe files)`);
